def reset_native(env, env_ids):
    robot = env.scene["robot"]
    kind = "kneel" if env.cfg.native_skill == "standup" else "stand"
    values = pose_values(kind)
    q = robot.data.default_joint_pos[env_ids].clone()
    for name, value in values.items(): q[:, robot.joint_names.index(name)] = value
    for follower, driver, multiplier in zip(Q1_INERTIA_MIMIC_JOINTS, Q1_INERTIA_MIMIC_DRIVERS, Q1_INERTIA_MIMIC_MULTIPLIERS):
        q[:, robot.joint_names.index(follower)] = q[:, robot.joint_names.index(driver)]*multiplier
    root = robot.data.default_root_state[env_ids].clone()
    root[:, :3] += env.scene.env_origins[env_ids]
    root[:, 2] = env.scene.env_origins[env_ids, 2]+reset_root_height(kind)
    root[:, 7:] = 0.
    robot.write_root_pose_to_sim(root[:, :7], env_ids=env_ids)
    robot.write_root_velocity_to_sim(root[:, 7:], env_ids=env_ids)
    robot.write_joint_state_to_sim(q, torch.zeros_like(q), env_ids=env_ids)


def native_curriculum(env, env_ids, start_iter=0, steps_per_iteration=24):
    iteration = start_iter+env.common_step_counter//steps_per_iteration
    s = env.command_manager.get_term("skill")
    if env.cfg.native_skill == "backflip":
        s.level = max(0., min(1., (iteration-500)/2500.))
    else:
        s.level = 1.
    if env.cfg.native_skill == "walk":
        level = max(0., min(1., iteration/3000.))
        velocity = env.command_manager.get_term("base_velocity")
        velocity.cfg.ranges.lin_vel_x = (-.4*level, 1.2*level)
        velocity.cfg.ranges.ang_vel_z = (-.5*level, .5*level)
    return s.level


def pose_tracking(env):
    s = skill(env); error = env.scene["robot"].data.joint_pos[:, s.pids]-s.reference()
    return torch.exp(-error.square().mean(-1)/.15)


def skill_height(env):
    s = skill(env); z = s.robot.data.root_pos_w[:, 2]-env.scene.env_origins[:, 2]
    target = torch.where(s.mode == MODES.index("kneel"), .45, .848686)
    target = torch.where(s.mode == MODES.index("standup"), .45+.398686*smooth(s.elapsed/3.5), target)
    target = torch.where((s.mode == MODES.index("backflip")) & s.landed, .45, target)
    flight = (s.mode == MODES.index("backflip")) & (s.has_air | (s.elapsed > .8)) & ~s.landed
    return torch.where(flight, torch.zeros_like(z), torch.exp(-(z-target).square()/.04))


def upright_reward(env):
    s = skill(env); r = s.robot.data
    active = (s.mode == MODES.index("backflip")) & (s.elapsed > .8) & ~s.landed
    return torch.where(active, torch.zeros_like(s.winding), (-r.projected_gravity_b[:, 2]).clamp_min(0))


def stand_reward(env):
    s = skill(env)
    return (s.hold > .1).float()+s.success.float()


def flip_reward(env):
    s = skill(env); r = s.robot.data
    progress = (-s.delta).clamp(0., .2)/env.step_dt
    jump = r.root_lin_vel_w[:, 2].clamp(0., 4.)
    launch = (s.elapsed > .8) & (s.elapsed < 1.5) & ~s.has_air
    return ((progress*s.has_air.float()+jump*launch.float()+5.*s.has_air.float()
             +30.*s.success.float()+10.*s.hold.clamp(max=1.)) * s.level
            * (s.mode == MODES.index("backflip")).float() * (~s.illegal).float())


def physical_failure(env):
    s = skill(env); r = s.robot.data
    z = r.root_pos_w[:, 2]-env.scene.env_origins[:, 2]
    flip = s.mode == MODES.index("backflip")
    minimum = torch.where(flip, .07, torch.where(s.mode == MODES.index("standup"), .22, .55))
    tilt = (-r.projected_gravity_b[:, 2] < .5) & ~flip
    env._native_last_illegal = s.illegal.clone()
    return (z < minimum) | tilt | s.illegal | ((r.root_pos_w[:, :2]-env.scene.env_origins[:, :2]).norm(dim=-1) > 4.)
