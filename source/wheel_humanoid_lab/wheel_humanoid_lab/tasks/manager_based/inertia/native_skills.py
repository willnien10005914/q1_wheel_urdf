from wheel_humanoid_lab.assets.q1_inertia import (
    Q1_INERTIA_DEFAULT_POS, Q1_INERTIA_POSITION_JOINTS, Q1_INERTIA_WHEEL_JOINTS,
    Q1_INERTIA_URDF, Q1_INERTIA_WHEEL_RADIUS,
    Q1_INERTIA_MIMIC_JOINTS, Q1_INERTIA_MIMIC_DRIVERS, Q1_INERTIA_MIMIC_MULTIPLIERS,
)

MODES = ("stand", "walk", "standup", "backflip", "kneel")
CONTRACT = "q1-native-manager-v2-23x90"


def smooth(x):
    x = x.clamp(0.0, 1.0)
    return x*x*x*(10.0-15.0*x+6.0*x*x)


def pose_values(kind):
    """CAD-native signs and physically valid ranges, without a virtual neck."""
    q = {j: Q1_INERTIA_DEFAULT_POS[j] for j in Q1_INERTIA_POSITION_JOINTS}
    values = {
        "stand": (.35, .70, .10, .35, .50),
        "kneel": (1.02, 2.36, .30, .30, 1.10),
        "load": (1.18, 2.12, .30, -.80, 1.10),
        "push": (-.65, .04, .04, 1.00, .30),
        "tuck": (-1.05, 2.35, .35, .50, 2.10),
    }[kind]
    hip, knee, waist, shoulder, elbow = values
    q.update(center_waist_Pitch_joint=waist)
    for side, leg_sign, arm_sign in (("left", 1., 1.), ("right", -1., -1.)):
        q[f"{side}_hip_Pitch_joint"] = leg_sign*hip
        q[f"{side}_knee_1_Pitch_joint"] = -leg_sign*knee
        q[f"{side}_shoulder_Pitch_joint"] = arm_sign*shoulder
        q[f"{side}_elbow_Pitch_joint"] = -arm_sign*elbow
    return q


@lru_cache(maxsize=None)
def reset_root_height(kind):
    """Ground the wheels using the actual upright, zero-roll CAD leg chain.

    This is reset geometry, not an external force or a dynamic balance solution.
    Horizontal hip-roll/knee origin offsets cancel in this source chain.
    """
    urdf=ET.parse(Q1_INERTIA_URDF).getroot()
    def origin(name):
        return [float(v) for v in urdf.find(f"joint[@name='{name}']/origin").get('xyz').split()]
    hip_origin=origin('left_hip_Pitch_joint')
    thigh_a=origin('left_hip_Roll_joint');thigh_b=origin('left_knee_1_Pitch_joint')
    shin=origin('left_wheel_Pitch_joint')
    q=pose_values(kind);hip=q['left_hip_Pitch_joint'];knee=q['left_knee_1_Pitch_joint']
    # R_y(-q) applied to [x,0,z] has z = x*sin(q)+z*cos(q).
    wheel_z=(hip_origin[2]+(thigh_a[0]+thigh_b[0])*math.sin(hip)
             +(thigh_a[2]+thigh_b[2])*math.cos(hip)
             +shin[0]*math.sin(hip+knee)+shin[2]*math.cos(hip+knee))
    return Q1_INERTIA_WHEEL_RADIUS-wheel_z+.002


class NativeSkillCommand(CommandTerm):
    def __init__(self, cfg, env):
        super().__init__(cfg, env)
        self.robot = env.scene["robot"]
        self.pids, _ = self.robot.find_joints(Q1_INERTIA_POSITION_JOINTS, preserve_order=True)
        self.wids, _ = self.robot.find_joints(Q1_INERTIA_WHEEL_JOINTS, preserve_order=True)
        self.feet, _ = self.robot.find_bodies(["left_wheel_link", "right_wheel_link"], preserve_order=True)
        self.support_names = ["left_wheel_link", "right_wheel_link", "left_calf_2_link", "right_calf_2_link"]
        self.sensor = env.scene["contact_forces"]
        self.support_ids, _ = self.sensor.find_bodies(self.support_names)
        self.illegal_ids = [i for i, n in enumerate(self.sensor.body_names) if n not in self.support_names]
        self.poses = {name: torch.tensor([pose_values(name)[j] for j in Q1_INERTIA_POSITION_JOINTS], device=self.device)
                      for name in ("stand", "kneel", "load", "push", "tuck")}
        self._command = torch.zeros(self.num_envs, 8, device=self.device)
        self.mode = torch.full((self.num_envs,), MODES.index(cfg.mode), dtype=torch.long, device=self.device)
        self.start_step = torch.zeros(self.num_envs, device=self.device)
        self.start_q = self.robot.data.joint_pos[:, self.pids].clone()
        self.anchor = self.robot.data.root_pos_w.clone()
        self.previous_quat = self.robot.data.root_quat_w.clone()
        self.flip_axis = torch.zeros(self.num_envs, 3, device=self.device); self.flip_axis[:, 1] = 1.
        self.winding = torch.zeros(self.num_envs, device=self.device)
        self.delta = self.winding.clone(); self.air_time = self.winding.clone()
        self.max_air_time = self.winding.clone(); self.takeoff_t = self.winding.clone()
        self.hold = self.winding.clone(); self.best_hold = self.winding.clone()
        self.has_air = torch.zeros(self.num_envs, dtype=torch.bool, device=self.device)
        self.landed = self.has_air.clone(); self.illegal = self.has_air.clone(); self.success = self.has_air.clone()
        self.tick = -1
        self.level = 0.0 if cfg.mode == "backflip" else 1.0
        self.metrics = {n: torch.zeros(self.num_envs, device=self.device) for n in
                        ("success", "hold_s", "backturn_rad", "airtime_s", "illegal_contact", "upright", "height_m")}

    @property
    def command(self):
        return self._command

    @property
    def elapsed(self):
        return (self._env.episode_length_buf.float()-self.start_step).clamp_min(0)*self._env.step_dt

    def set_mode(self, name, env_ids=None):
        if name not in MODES:
            raise ValueError(name)
        ids = self.robot._ALL_INDICES if env_ids is None or isinstance(env_ids, slice) else env_ids
        self.mode[ids] = MODES.index(name)
        self.start_step[ids] = self._env.episode_length_buf[ids].float()
        self.start_q[ids] = self.robot.data.joint_pos[ids][:, self.pids]
        self.anchor[ids] = self.robot.data.root_pos_w[ids]
        self.previous_quat[ids] = self.robot.data.root_quat_w[ids]
        axis = quat_apply(self.robot.data.root_quat_w[ids], torch.tensor([0., 1., 0.], device=self.device).expand(len(ids), -1))
        self.flip_axis[ids] = axis
        for buffer in (self.winding, self.delta, self.air_time, self.max_air_time, self.takeoff_t, self.hold, self.best_hold):
            buffer[ids] = 0.
        for buffer in (self.has_air, self.landed, self.illegal, self.success):
            buffer[ids] = False
        self._update_command()

    def _resample_command(self, env_ids):
        self.set_mode(self.cfg.mode, env_ids)

    def update_state(self):
        if self.tick == self._env.common_step_counter:
            return
        self.tick = self._env.common_step_counter
        r = self.robot.data
        dq = quat_mul(r.root_quat_w, quat_conjugate(self.previous_quat))
        dq = torch.where(dq[:, :1] < 0, -dq, dq)
        v = dq[:, 1:]; norm = v.norm(dim=-1)
        self.delta = 2*torch.atan2(norm, dq[:, 0])*(v*self.flip_axis).sum(-1)/norm.clamp_min(1e-8)
        self.winding += self.delta
        self.previous_quat.copy_(r.root_quat_w)
        forces = self.sensor.data.net_forces_w.norm(dim=-1)
        airborne = (forces < 5.).all(-1)
        self.air_time = torch.where(airborne, self.air_time+self._env.step_dt, torch.zeros_like(self.air_time))
        self.max_air_time = torch.maximum(self.max_air_time, self.air_time)
        lift = airborne & (r.root_lin_vel_w[:, 2] > .15) & (self.elapsed > .5)
        new_air = lift & ~self.has_air
        self.takeoff_t[new_air] = self.elapsed[new_air]
        self.has_air |= lift
        support = (forces[:, self.support_ids] > 8.).sum(-1)
        self.landed |= self.has_air & (self.elapsed-self.takeoff_t > .12) & (support > 0)
        self.illegal |= (forces[:, self.illegal_ids] > 20.).any(-1)
        upright = -r.projected_gravity_b[:, 2]
        z = r.root_pos_w[:, 2]-self._env.scene.env_origins[:, 2]
        still = (r.root_ang_vel_b.norm(dim=-1) < 1.) & (r.root_lin_vel_b[:, :2].norm(dim=-1) < .35)
        flip_ok = (self.winding+2*math.pi).abs() < .4
        flip = self.mode == MODES.index("backflip")
        stable = (upright > .93) & still & (support >= 2) & ~self.illegal
        achieved = torch.where(flip, stable & flip_ok & (self.max_air_time > .06), stable & (z > .70))
        self.hold = torch.where(achieved, self.hold+self._env.step_dt, torch.zeros_like(self.hold))
        self.best_hold = torch.maximum(self.best_hold, self.hold)
        self.success |= self.hold >= 1.0

    def _update_metrics(self):
        self.update_state()
        r = self.robot.data
        for name, value in {"success": self.success.float(), "hold_s": self.best_hold,
                            "backturn_rad": (-self.winding).clamp_min(0), "airtime_s": self.max_air_time,
                            "illegal_contact": self.illegal.float(), "upright": -r.projected_gravity_b[:, 2],
                            "height_m": r.root_pos_w[:, 2]-self._env.scene.env_origins[:, 2]}.items():
            self.metrics[name].copy_(value)

    def _update_command(self):
        self._command.zero_()
        self._command.scatter_(1, self.mode[:, None], 1.)
        timed = (self.mode != MODES.index("stand")) & (self.mode != MODES.index("walk"))
        self._command[:, 5] = torch.where(timed, (self.elapsed/6.).clamp(max=2.), 0.)
        self._command[:, 6] = self.winding/(2*math.pi)
        self._command[:, 7] = self.max_air_time.clamp(max=2.)

    def reference(self):
        t = self.elapsed
        stand = self.poses["stand"].expand(self.num_envs, -1)
        kneel = self.poses["kneel"].expand_as(stand)
        ref = stand.clone()
        rise = self.mode == MODES.index("standup")
        lower = self.mode == MODES.index("kneel")
        ref = torch.where(rise[:, None], self.start_q+(stand-self.start_q)*smooth(t/3.5)[:, None], ref)
        ref = torch.where(lower[:, None], self.start_q+(kneel-self.start_q)*smooth(t/3.)[:, None], ref)
        load, push, tuck = [self.poses[n].expand_as(stand) for n in ("load", "push", "tuck")]
        flip_ref = stand+(load-stand)*smooth((t-.45)/.55)[:, None]
        flip_ref = torch.where((t >= 1.)[:, None], load+(push-load)*smooth((t-1.)/.18)[:, None], flip_ref)
        flip_ref = torch.where(self.has_air[:, None], push+(tuck-push)*smooth((t-self.takeoff_t-.02)/.14)[:, None], flip_ref)
        extend = ((-self.winding > 5.0) & (self.robot.data.root_lin_vel_w[:, 2] < .8)) | self.landed
        flip_ref = torch.where(extend[:, None], kneel, flip_ref)
        flip_ref = stand+self.level*(flip_ref-stand)
        ref = torch.where((self.mode == MODES.index("backflip"))[:, None], flip_ref, ref)
        # Brief handover blend changes motor targets, never simulation state.
        return self.start_q+(ref-self.start_q)*smooth(t/.35)[:, None]


